/**
 * Root layout shared by every page of the application.
 *
 * The props type is declared explicitly instead of using the global `LayoutProps`
 * generated by Next.js, which only exists after a first build and would make
 * typecheck fail on a fresh clone.
 *
 * @param props - Layout props.
 * @param props.children - Page content, which provides its own `<main>`.
 * @returns The `<html>` document of the application.
 */
export default function RootLayout({ children }: { children: ReactNode }) {
  return (
    <html lang="fr">
      <body>{children}</body>
    </html>
  )
}
