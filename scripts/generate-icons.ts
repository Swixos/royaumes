/**
 * Generates the icon set of the interface from Game Icons (https://game-icons.net), by its
 * authors (Lorc, Delapouite and contributors), under the CC BY 3.0 license. Only the icons
 * the game uses are copied, as plain SVG paths, so the browser never loads the whole set.
 *
 *   pnpm exec tsx scripts/generate-icons.ts
 *
 * The result, `src/ui/game-icons.ts`, is versioned; this script is run again after a
 * change of the list below.
 *
 * @packageDocumentation
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

/** Icon of each entity or interface element, by Game Icons name. */
const ICONS: Record<string, string> = {
  brand: 'tower-flag',
  village: 'medieval-gate',
  wood: 'wood-pile',
  stone: 'stone-block',
  gold: 'two-coins',
  sawmill: 'circular-saw',
  quarry: 'war-pick',
  mine: 'mine-wagon',
  senate: 'greek-temple',
  warehouse: 'barn',
  wall: 'stone-wall',
  shipyard: 'ship-wheel',
  build: 'hammer-nails',
  capacity: 'wooden-crate',
  dungeon: 'dungeon-gate',
  hero: 'visored-helm',
  companion: 'robot-golem',
  goblin: 'goblin-head',
  skeleton: 'skeleton',
  troll: 'troll',
  door: 'wooden-door',
  ranking: 'laurels-trophy',
  market: 'scales',
  tavern: 'beer-stein',
  fleet: 'galleon',
  trireme: 'trireme',
  pirates: 'pirate-flag',
  harbor: 'anchor',
  ram: 'ship-bow',
  board: 'pirate-hook',
  blockade: 'crossed-chains',
  account: 'scroll-unfurled',
  logout: 'exit-door',
  defense: 'checked-shield',
  time: 'hourglass',
  search: 'spyglass',
  compass: 'compass',
  swords: 'crossed-swords',
  sunk: 'sinking-ship',
  wave: 'big-wave',
  chat: 'conversation',
  rank: 'rank-3',
  loot: 'swap-bag',
}

const require = createRequire(import.meta.url)
const set = JSON.parse(readFileSync(require.resolve('@iconify-json/game-icons/icons.json'), 'utf8'))

const entries = Object.entries(ICONS).map(([kind, name]) => {
  const icon = set.icons[name]
  if (!icon) throw new Error(`Icône inconnue : ${name}`)
  const paths = [...String(icon.body).matchAll(/ d="([^"]+)"/g)].map((match) => match[1])
  if (paths.length === 0) throw new Error(`Icône sans tracé : ${name}`)
  return `  ${JSON.stringify(kind)}: ${JSON.stringify(paths)},`
})

writeFileSync(
  'src/ui/game-icons.ts',
  `/**
 * Icons of the interface, generated by \`scripts/generate-icons.ts\` from Game Icons
 * (https://game-icons.net), by Lorc, Delapouite and contributors, under the CC BY 3.0
 * license (https://creativecommons.org/licenses/by/3.0/). Each icon is a list of SVG
 * paths in a 512 by 512 grid.
 *
 * @packageDocumentation
 */

/** SVG paths of each icon, by entity or interface element. */
export const GAME_ICONS: Record<string, string[]> = {
${entries.join('\n')}
}
`,
)
console.log(`${entries.length} icônes écrites dans src/ui/game-icons.ts`)
